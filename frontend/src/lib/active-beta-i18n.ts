const DYNAMIC_PATTERNS: ReadonlyArray<{
  match: RegExp;
  ja: (...groups: string[]) => string;
}> = [
  { match: /^(Good morning|Good afternoon|Good evening), (.+) 👋$/, ja: (_all, greeting, name) => `${ACTIVE_BETA_JA[greeting]}、${name}さん 👋` },
  { match: /^as of (.+)$/, ja: (_all, value) => `更新: ${value}` },
  { match: /^updated as of (.+)$/, ja: (_all, value) => `更新: ${value}` },
  { match: /^(\d+) trades$/, ja: (_all, value) => `${value}件の取引` },
  { match: /^(\d+) similar historical conditions observed$/, ja: (_all, value) => `類似する過去の市場環境を${value}件観測` },
  { match: /^Average historical quality (.+)$/, ja: (_all, value) => `過去データの平均品質 ${value}` },
  { match: /^(\d+) cautions? noted in current research$/, ja: (_all, value) => `現在の調査で${value}件の注意事項` },
  { match: /^\+(\d+) more$/, ja: (_all, value) => `他${value}件` },
  { match: /^(.+) confidence$/, ja: (_all, value) => `${localizeActiveBetaCopy("ja", value)}の信頼度` },
  { match: /^Observed PnL: (.+)$/, ja: (_all, value) => `観測損益: ${value}` },
  { match: /^(.+)% of equity$/, ja: (_all, value) => `有効証拠金比 ${value}%` },
  { match: /^Key Events \((.*)\)$/, ja: (_all, value) => value ? `主なイベント（${value}）` : "主なイベント" },
  { match: /^Research Evidence \((.*)\)$/, ja: (_all, value) => value ? `調査根拠（${value}）` : "調査根拠" },
];

export function localizeActiveBetaCopy(lang: Lang, value: string): string {
  if (lang === "en" || !value) return value;
  const normalized = value.replace(/\s+/g, " ").trim();
  const prefix = /^\s/.test(value) ? " " : "";
  const suffix = /\s$/.test(value) ? " " : "";
  const exact = ACTIVE_BETA_JA[normalized];
  if (exact) return `${prefix}${exact}${suffix}`;
  for (const pattern of DYNAMIC_PATTERNS) {
    const match = normalized.match(pattern.match);
    if (match) return `${prefix}${pattern.ja(...match)}${suffix}`;
  }
  return value;
}

type CustomerAccountDisplay = {
  name?: string | null;
  brokerName?: string | null;
  accountNumber?: string | null;
};

/**
 * Formats customer-owned account identity without exposing an internal PK.
 *
 * Duplicate generic workspace labels collapse to one useful label, the
 * broker-facing MT5 account number is retained, and unknown real broker names
 * pass through unchanged as proper names.
 */
export function formatCustomerAccountDisplay(
  lang: Lang,
  account: CustomerAccountDisplay,
  fallback = "Trading account",
): string {
  const number = String(account.accountNumber || "").trim();
  const labels = [account.brokerName, account.name]
    .map((value) => String(value || "").trim())
    .filter((value, index, all) => value && all.findIndex((candidate) => candidate.toLocaleLowerCase() === value.toLocaleLowerCase()) === index)
    .map((value) => localizeActiveBetaCopy(lang, value));

  if (number && !labels.some((value) => value.includes(number))) labels.push(number);
  if (labels.length) return labels.join(" · ");
  return number || localizeActiveBetaCopy(lang, fallback);
}

